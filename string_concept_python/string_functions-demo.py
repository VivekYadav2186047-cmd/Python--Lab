'''String Methods and Functions
Take the string "  i love python programming  " and:

Remove extra spaces from both ends
Convert it to title case
Count how many times "o" appears'''

text = " i love python programming "
print("Remove extra spaces from both ends")

print(text.strip())

print("Convert it to title case")

print(text.title())

print("Count how many times 'o' appears")

print(text.count("o"))
